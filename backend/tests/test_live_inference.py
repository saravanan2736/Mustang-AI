"""
Live Inference Integration Test
Verifies authentic local execution against the real llama-server executable and NVIDIA RTX 5050 GPU.
"""

import asyncio
import pytest
from pathlib import Path

from app.config import settings
from app.core.engine_base import (
    ChatCompletionRequest,
    ChatMessage,
    EngineConfig,
    EngineState,
)
from app.core.llama_engine import LlamaServerEngine
from app.core.memory_estimator import estimate_model_memory


@pytest.mark.gpu
@pytest.mark.asyncio
async def test_real_llama_cuda_inference():
    """
    End-to-End Live GPU Inference Test:
    Spawns real llama-server.exe, offloads to RTX 5050 Laptop GPU,
    validates authoritative VRAM allocation, streams real tokens, and shuts down cleanly.
    """
    model_path = settings.MODELS_DIR / "qwen2.5-0.5b-instruct-q4_k_m.gguf"
    if not model_path.exists():
        pytest.skip(f"Test model not yet present: {model_path}")

    # 1. Test Advisory Pre-flight Estimator
    estimate = estimate_model_memory(model_path, requested_gpu_layers=99, target_ctx=2048)
    assert estimate.estimate_available is True
    assert estimate.architecture == "qwen2"
    assert estimate.total_layers >= 24
    assert estimate.fit_status in ("FULL_GPU_SAFE", "TIGHT_MARGIN")

    # 2. Spawn Real llama-server.exe
    engine = LlamaServerEngine()
    config = EngineConfig(
        model_path=model_path,
        n_gpu_layers=99,
        n_ctx=2048,
        n_batch=512,
        port=18080,
        host="127.0.0.1",
        flash_attention=True,
    )

    started = await engine.start(config)
    assert started is True, "Failed to start real llama-server process"

    try:
        # 3. Verify Authoritative Metrics
        status = await engine.get_status()
        assert status.state == EngineState.READY
        assert status.gpu_layers_offloaded > 0, "No layers offloaded to GPU!"
        assert status.vram_allocated_mb > 0.0, "Authoritative VRAM was not reported!"
        assert status.pid is not None

        # 4. Stream Actual Inference Tokens
        req = ChatCompletionRequest(
            messages=[
                ChatMessage(
                    role="user",
                    content="Hello! State in one sentence what Mustang AI is.",
                )
            ],
            temperature=0.7,
            max_tokens=64,
            stream=True,
        )

        tokens = []
        async for chunk in engine.stream_chat(req):
            if chunk.delta_content:
                tokens.append(chunk.delta_content)

        assert len(tokens) > 0, "No tokens were generated by local model!"
        full_text = "".join(tokens)
        assert len(full_text.strip()) > 5

        # Confirm tokens/second performance was measured
        final_status = await engine.get_status()
        assert final_status.active_tokens_per_sec > 0.0

    finally:
        # 5. Clean Model Unload & Resource Reclamation
        await engine.stop()
        status_after = await engine.get_status()
        assert status_after.state == EngineState.UNLOADED
